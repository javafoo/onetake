import type { ClipModel } from "../content/clip-options";

import { OMNI_MODEL, OMNI_PRICE_PER_SECOND_USD, omniSeconds } from "./omni";

/* What every clip provider shares: the state a poll reads, the model each
   product id is generated by, and the list price per clip. Gemini Omni is the
   only clip provider, so these are thin; they stay separate so the job layer
   never imports a provider client for a type. */

export type ClipState =
  | { state: "pending"; status: string }
  | { state: "completed"; status: string; videoUrl: string }
  | { state: "failed"; status: string; message: string };

/** The model each clip id the product sells is generated by. */
export const CLIP_ENDPOINT: Record<ClipModel, string> = {
  omni: OMNI_MODEL,
};

/** Who makes each model's clips, for the job row and the cost record. */
export function clipProviderOf(model: ClipModel): "google" {
  void model;
  return "google";
}

/** The seconds a clip is made at: clamped to what the model accepts rather than refused. */
export function clipSeconds(requested: number | undefined, model: ClipModel = "omni"): number {
  void model;
  return omniSeconds(requested);
}

const PRICE_PER_SECOND_USD: Record<string, number> = { [OMNI_MODEL]: OMNI_PRICE_PER_SECOND_USD };

/** The provider's list price for one clip, or undefined if we have none on file. */
export function clipPriceUsd(endpoint: string, seconds: number): number | undefined {
  const perSecond = PRICE_PER_SECOND_USD[endpoint];
  return perSecond === undefined ? undefined : perSecond * seconds;
}
